#include "libft.h"

void	*ft_memset(void *dest, int ch, size_t count)
{
	unsigned char	*ptr;
	size_t			i;

	ptr = (unsigned char *)dest;
	i = 0;
	while (i < count)
	{
		ptr[i] = (unsigned char)ch;
		i++;
	}
	return (dest);
}
